// Generates static SVG paths for the LATAM presence map.
// Usage: npx tsx scripts/build-latam-map.ts
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { geoPath } from 'd3-geo'
import { feature, merge } from 'topojson-client'
import type { GeometryCollection, Topology } from 'topojson-specification'
import { latamProjection } from '../lib/geo/latam-projection'

const require = createRequire(import.meta.url)
const world50 = require('world-atlas/countries-50m.json') as Topology
const world110 = require('world-atlas/countries-110m.json') as Topology

const COUNTRIES: Record<string, string> = {
  Mexico: 'mx',
  Guatemala: 'gt',
  Belize: 'bz',
  Honduras: 'hn',
  'El Salvador': 'sv',
  Nicaragua: 'ni',
  'Costa Rica': 'cr',
  Panama: 'pa',
  Colombia: 'co',
  Venezuela: 've',
}

const path = geoPath(latamProjection()).digits(1)

type Countries = GeometryCollection<{ name: string }>
type Polygons = Parameters<typeof merge>[1]

const ctx = world110.objects.countries as Countries
const contextPath = path(merge(world110, ctx.geometries as Polygons)) ?? ''

const countries = world50.objects.countries as Countries
const countryPaths: Record<string, string> = {}
for (const g of countries.geometries) {
  const name = (g.properties as { name?: string } | undefined)?.name
  const code = name && COUNTRIES[name]
  if (!code) continue
  countryPaths[code] = path(feature(world50, g)) ?? ''
}

const out = `// Generated by scripts/build-latam-map.ts. Do not edit.
export const CONTEXT_PATH = ${JSON.stringify(contextPath)}
export const COUNTRY_PATHS: Record<string, string> = ${JSON.stringify(countryPaths, null, 2)}
`
writeFileSync(new URL('../lib/geo/latam-map-data.ts', import.meta.url), out)
console.log(`context ${contextPath.length} chars, countries ${Object.keys(countryPaths).join(', ')}`)
